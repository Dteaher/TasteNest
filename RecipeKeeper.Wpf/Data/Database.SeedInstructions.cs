    private static string GetSeedRecipeInstructions(string title, string fallback)
    {
        return SeedRecipeInstructions.TryGetValue(title, out var instructions)
            ? instructions
            : fallback.Trim();
    }

    private static void RepairSeedRecipeInstructions(SqlConnection connection)
    {
        foreach (var recipe in SeedRecipeInstructions)
        {
            using var command = connection.CreateCommand();
            command.CommandText = """
                UPDATE dbo.Recipes
                SET Instructions = @instructions
                WHERE Title = @title
                  AND UserId IS NULL
                """;
            command.Parameters.AddWithValue("@title", recipe.Key);
            command.Parameters.AddWithValue("@instructions", recipe.Value);
            command.ExecuteNonQuery();
        }
    }
